#!/usr/bin/env python3
"""thermal_pcb.py — тепловой расчёт платы Krystal Radio (SDR, direct conversion).

Уровни расчёта
--------------
fast  — узловая (аналитическая) модель T_j = Ta + P·theta_JA;
        параметры θ_JA, T_j,max — из даташитов. Быстро, идёт в CI.

fem   — 2D FEM теплопроводности по контуру платы из PCB CAD
        (hardware/tscircuit/out/circuit.json); источники Q берутся из
        ngspice (`sim/netlists/thermal_bias.cir`, анализ `.op`) — стандартная
        electro-thermal связка «электрика → потери → температура».

    Уравнение теплопроводности усреднено по толщине (heat-spreading):
        −∇·(k·t·∇T) + h·(T − T_a) = q(x,y)
    k — эффективная теплопроводность в плоскости (медь + FR4),
    t — толщина платы, h = h_top + h_bot (конвекция с двух сторон),
    q — поверхностная плотность мощности, края адиабатические.

 3D FEM (Elmer/CalculiX) — следующий уровень; для платы 1.6 мм 2D достаточно.

Выход: sim/outputs/thermal_fast.json, sim/outputs/thermal_fem.json.
Код возврата 0, если T_j в допуске.
"""

from __future__ import annotations

import argparse
import json
import re
import subprocess
from pathlib import Path

import numpy as np
from scipy.sparse import coo_matrix
from scipy.sparse.linalg import spsolve

# --------------------------------------------------------------------------
# электрический режим (DC) — источники тепла
# --------------------------------------------------------------------------
RAIL = 3.3          # шина 3.3 В
VIN = 5.0           # вход LDO

# (имя нагрузки, ток, A) — модель DC-потребления по блокам
BIAS_LOADS = [
    ("r_mcu", 0.025),   # U1  STM32F103C8T6
    ("r_af",  0.015),   # RF-тракт (Q_LNA1/Q_LNA2 + фильтр)
    ("r_mix", 0.010),   # U_MIX (LT5560)
    ("r_op",  0.010),   # baseband-буферы
]

# какой посадочной площадке на плате принадлежит мощность
POWER_ASSIGN = {
    "r_ldo": ["U_LDO"],
    "r_mcu": ["U1"],
    "r_af":  ["Q_LNA1", "Q_LNA2"],
    "r_mix": ["U_MIX1"],
    "r_op":  ["U_OP1"],
}

# fast-модель: theta_JA (°C/Вт) и T_j,max (°C) из даташитов
THETA_JA = {
    "U1":     (55.0,  85.0),   # STM32F103, LQFP48, JEDEC 2s2p
    "U_LDO":  (65.0, 125.0),   # AMS1117 SOT-223 с полигоном
    "U_MIX1": (95.0,  85.0),   # LT5560
    "U_OP1":  (120.0, 125.0),  # операционный усилитель
    "Q_LNA1": (180.0, 150.0),  # SOT-23
    "Q_LNA2": (180.0, 150.0),
}
DEFAULT_THETA = (150.0, 125.0)

# материалы / теплоотвод
K_COPPER = 385.0    # W/mK
K_FR4 = 0.30        # W/mK
CU_THICKNESS = 0.035e-3  # 35 µm (1 oz)
H_CONV = 20.0       # W/m²K с двух сторон (естественная конвекция + КП)


# --------------------------------------------------------------------------
# входные данные
# --------------------------------------------------------------------------
def load_board(cad_path: Path):
    """Контур платы и посадочные места компонентов из PCB CAD (circuit.json)."""
    data = json.loads(Path(cad_path).read_text())
    names = {e["source_component_id"]: e.get("name", "?")
             for e in data if e.get("type") == "source_component"}
    board, comps = None, []
    for e in data:
        t = e.get("type")
        if t == "pcb_board":
            board = dict(width=float(e["width"]), height=float(e["height"]),
                         thickness=float(e.get("thickness", 1.6)),
                         layers=int(e.get("num_layers", 2)),
                         material=e.get("material", "fr4"))
        elif t == "pcb_component":
            c = e.get("center", {})
            comps.append(dict(name=names.get(e.get("source_component_id"), "?"),
                              x=float(c.get("x", 0.0)), y=float(c.get("y", 0.0)),
                              w=float(e.get("width", 1.0)),
                              h=float(e.get("height", 1.0))))
    if board is None:
        raise SystemExit(f"no pcb_board in {cad_path}")
    return board, comps


def k_in_plane(board):
    """Эффективная теплопроводность в плоскости: медь + FR4."""
    n = max(board["layers"], 1)
    t = board["thickness"] * 1e-3
    f_cu = min(1.0, n * 0.035e-3 / max(t, 1e-6))
    return f_cu * K_COPPER + (1.0 - f_cu) * 0.30, f_cu


def run_ngspice(work: Path):
    """Сгенерировать DC-деск нагрузки, выполнить ngspice .op, снять мощности."""
    work.mkdir(parents=True, exist_ok=True)
    i_tot = sum(i for _, i in BIAS_LOADS)
    lines = ["* thermal bias deck - generated by thermal_pcb.py",
             f"v_vin vin 0 dc {VIN}",
             f"r_ldo vin v3v3 {(VIN - RAIL) / i_tot:.6f}"]
    for nm, i in BIAS_LOADS:
        lines.append(f"{nm} v3v3 0 {RAIL / i:.6f}")
    lines += [".control", "op", "print v(v3v3)", "print i(v_vin)"]
    for nm, _ in BIAS_LOADS:
        lines.append(f"print @{nm}[p]")
    lines += ["print @r_ldo[p]", ".endc", ".end", ""]

    deck = Path(work) / "thermal_bias.cir"
    deck.write_text("\n".join(lines))
    r = subprocess.run(["ngspice", "-b", str(deck)],
                       capture_output=True, text=True)
    (Path(work) / "thermal_bias.log").write_text(r.stdout + "\n" + r.stderr)
    if r.returncode != 0:
        raise SystemExit(f"ngspice rc={r.returncode}\n{r.stdout[-1500:]}")

    vals = {m.group(1): float(m.group(2)) for m in re.finditer(
        r"^\s*([@\w().\[\]]+)\s*=\s*([-+0-9.eE]+)", r.stdout, re.M)}
    powers = {nm: abs(vals.get(f"@{nm}[p]", 0.0)) for nm, _ in BIAS_LOADS}
    powers["r_ldo"] = abs(vals.get("@r_ldo[p]", 0.0))
    return dict(powers=powers, total_w=sum(powers.values()),
                v_rail=vals.get("v(v3v3)", RAIL),
                i_total=abs(vals.get("i(v_vin)", 0.0)),
                deck=str(deck))


def build_sources(powers, comps):
    """Мощности ngspice → источники на посадочных местах CAD."""
    by_name = {c["name"]: c for c in comps}
    src = []
    for pname, refs in POWER_ASSIGN.items():
        p = powers.get(pname, 0.0)
        if p <= 0 or not refs:
            continue
        hits = [r for r in refs if r in by_name]
        if not hits:
            continue
        for ref in hits:
            c = by_name[ref]
            src.append(dict(ref=ref, p_w=p / len(hits), x=c["x"], y=c["y"],
                            w=c["w"], h=c["h"]))
    return src


def fast_model(powers, comps, ta):
    """Аналитика: T_j = T_a + P·θ_JA по каждому прибору."""
    by_name = {c["name"]: c for c in comps}
    rows = []
    for pname, refs in POWER_ASSIGN.items():
        p = powers.get(pname, 0.0)
        if p <= 0 or not refs:
            continue
        for ref in refs:
            if ref not in by_name:
                continue
            pj = p / len(refs)
            theta, tjmax = THETA_JA.get(ref, DEFAULT_THETA)
            tj = ta + pj * theta
            rows.append(dict(ref=ref, p_w=pj, theta_ja=theta, tj_c=tj,
                             tj_max_c=tjmax, margin_c=tjmax - tj,
                             pass_=bool(tj <= tjmax)))
    return dict(ta_c=ta, devices=rows,
                worst_tj_c=max((r["tj_c"] for r in rows), default=ta),
                pass_=all(r["pass_"] for r in rows))


def _fem_assemble(board, sources, k_in, h_conv, ta, nx=88, ny=84):
    """Сборка и решение 2D FEM (чистая реализация без дублей отладки)."""
    W = board["width"] * 1e-3
    H = board["height"] * 1e-3
    t = board["thickness"] * 1e-3
    dx, dy = W / nx, H / ny
    cell_a = dx * dy
    NX, NY = nx + 1, ny + 1

    def nid(i, j):
        return j * NX + i

    xs = np.arange(NX) * dx
    ys = np.arange(NY) * dy
    X, Y = np.meshgrid(xs, ys)
    coords = np.column_stack([X.ravel(), Y.ravel()])

    q_cell = np.zeros(nx * ny)
    src_cells = {}
    for k, s in enumerate(sources):
        cx = s["x"] * 1e-3 + W / 2.0
        cy = s["y"] * 1e-3 + H / 2.0
        hw = max(abs(s["w"]) * 1e-3 / 2.0, dx)
        hh = max(abs(s["h"]) * 1e-3 / 2.0, dy)
        i0 = int(np.clip((cx - hw) / dx, 0, nx - 1))
        i1 = int(np.clip((cx + hw) / dx, 0, nx - 1))
        j0 = int(np.clip((cy - hh) / dy, 0, ny - 1))
        j1 = int(np.clip((cy + hh) / dy, 0, ny - 1))
        idx = [j * nx + i for j in range(j0, j1 + 1) for i in range(i0, i1 + 1)]
        if not idx:
            idx = [int(np.clip(cy / dy, 0, ny - 1)) * nx
                   + int(np.clip(cx / dx, 0, nx - 1))]
        q_cell[idx] += s["p_w"] / (len(idx) * cell_a)
        src_cells[k] = idx

    n_nodes = NX * NY
    rows, cols, vals = [], [], []
    f = np.zeros(n_nodes)

    def add(a, b, v):
        for aa, bb, vv in zip(a, b, v):
            rows.append(aa); cols.append(bb); vals.append(vv)

    tris = np.array([[0, 1, 2], [0, 2, 3]])
    for j in range(ny):
        for i in range(nx):
            n = [nid(i, j), nid(i + 1, j), nid(i + 1, j + 1), nid(i, j + 1)]
            pc = coords[n]
            q = q_cell[j * nx + i]
            for tri in tris:
                a, b, c = (int(n[tri[0]]), int(n[tri[1]]), int(n[tri[2]]))
                pa, pb, pcc = coords[a], coords[b], coords[c]
                area = 0.5 * abs((pb[0] - pa[0]) * (pcc[1] - pa[1])
                                 - (pcc[0] - pa[0]) * (pb[1] - pa[1]))
                if area <= 1e-18:
                    continue
                b1 = pb[1] - pcc[1]; b2 = pcc[1] - pa[1]; b3 = pa[1] - pb[1]
                c1 = pcc[0] - pb[0]; c2 = pa[0] - pcc[0]; c3 = pb[0] - pa[0]
                B = np.array([[b1, b2, b3], [c1, c2, c3]]) / (2.0 * area)
                ke = k_in * t * area * (B.T @ B)
                me = h_conv * area / 12.0 * np.array([[2, 1, 1], [1, 2, 1], [1, 1, 2]])
                ke = ke + me
                nn = [a, b, c]
                for u in range(3):
                    for v in range(3):
                        rows.append(nn[u]); cols.append(nn[v]); vals.append(ke[u, v])
                    f[nn[u]] += q * area / 3.0 + h_conv * ta * area / 3.0

    A = coo_matrix((vals, (rows, cols)), shape=(n_nodes, n_nodes)).tocsr()
    T = spsolve(A, f)

    Tw = T.reshape(NY, NX)
    src_t = {}
    for k, s in enumerate(sources):
        vs = []
        for ci in src_cells[k]:
            vs.append(Tw[ci // nx, ci % nx])
        src_t[f"{s['ref']}#{k}"] = float(max(vs)) if vs else float("nan")

    q_total = float((q_cell * cell_a).sum())
    # сток считаем в той же FE-квадратуре, что и сборку: h·∫(T−Ta) dA
    sink = 0.0
    for j in range(ny):
        for i in range(nx):
            n = [nid(i, j), nid(i + 1, j), nid(i + 1, j + 1), nid(i, j + 1)]
            for tri in tris:
                a, b, c = int(n[tri[0]]), int(n[tri[1]]), int(n[tri[2]])
                pa, pb, pcc = coords[a], coords[b], coords[c]
                area = 0.5 * abs((pb[0] - pa[0]) * (pcc[1] - pa[1])
                                 - (pcc[0] - pa[0]) * (pb[1] - pa[1]))
                sink += h_conv * area * ((T[a] + T[b] + T[c]) / 3.0 - ta)
    return dict(t_max_c=float(T.max()), t_min_c=float(T.min()),
                t_avg_c=float(T.mean()), nodes=n_nodes, n_tri=2 * nx * ny,
                k_in_w_mk=k_in, h_conv_w_m2k=h_conv,
                q_total_w=q_total, sink_w=sink,
                energy_balance_w=abs(q_total - sink), sources=src_t,
                nx=nx, ny=ny)


def default_cad(root: Path) -> Path:
    """Опубликованный CAD (out/circuit.json) или рабочая копия эмиттера."""
    for rel in ("out/circuit.json", "hardware/tscircuit/out/circuit.json"):
        p = root / rel
        if p.exists():
            return p
    return root / "out/circuit.json"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Krystal Radio thermal (CAD + ngspice)")
    root = Path(__file__).resolve().parents[2]
    ap.add_argument("--cad", default=str(default_cad(root)))
    ap.add_argument("--out", default=str(Path(__file__).resolve().parents[1] / "outputs"))
    ap.add_argument("--ta", type=float, default=25.0)
    args = ap.parse_args(argv)

    out = Path(args.out)
    work = Path(__file__).resolve().parents[1] / "work" / "thermal"

    board, comps = load_board(Path(args.cad))
    k_in, f_cu = k_in_plane(board)
    print(f"[thermal] board {board['width']:.1f}x{board['height']:.1f} mm, "
          f"t={board['thickness']} mm, layers={board['layers']}, "
          f"k_in={k_in:.1f} W/mK (f_Cu={f_cu:.3f}), comps={len(comps)}")

    bias = run_ngspice(work)
    print(f"[ngspice] V_rail={bias['v_rail']:.3f} V  I={bias['i_total']*1e3:.1f} mA  "
          f"P_total={bias['total_w']*1e3:.1f} mW")
    for nm in ("r_ldo", "r_mcu", "r_af", "r_mix", "r_op"):
        print(f"          {nm:6s} {bias['powers'][nm]*1e3:7.2f} mW")

    sources = build_sources(bias["powers"], comps)
    fast = fast_model(bias["powers"], comps, args.ta)
    fem = _fem_assemble(board, sources, k_in, H_CONV, args.ta)

    out.mkdir(parents=True, exist_ok=True)
    (out / "thermal_fast.json").write_text(json.dumps(
        dict(board=board, ngspice=bias, fast=fast), indent=2))
    (out / "thermal_fem.json").write_text(json.dumps(
        dict(board=board, assets=dict(k_in_w_mk=k_in, f_cu=f_cu,
                                      h_conv=H_CONV, ta_c=args.ta),
             sources=[{k: v for k, v in s.items()} for s in sources], fem=fem),
        indent=2))

    print("\n[fast] T_j = T_a + P·θ_JA")
    for r in sorted(fast["devices"], key=lambda r: -r["tj_c"]):
        print(f"        {r['ref']:7s} P={r['p_w']*1e3:6.2f} mW  θ={r['theta_ja']:5.0f} "
              f"→ T_j={r['tj_c']:6.1f} °C (max {r['tj_max_c']:.0f})  "
              f"{'PASS' if r['pass_'] else 'FAIL'}")
    print(f"        worst T_j = {fast['worst_tj_c']:.1f} C  -> "
          f"{'PASS' if fast['pass_'] else 'FAIL'}")

    print(f"[fem]     T_max={fem['t_max_c']:.2f} C  T_avg={fem['t_avg_c']:.2f} C  "
          f"({fem['nodes']} nodes, {fem['n_tri']} triangles)")
    print(f"          energy balance |Q - h·(T-Ta)| = {fem['energy_balance_w']*1e3:.4f} mW")
    for ref, tv in sorted(fem["sources"].items(), key=lambda kv: -kv[1]):
        print(f"          {ref:14s} T={tv:.2f} C")

    print(f"\nJSON: {out/'thermal_fast.json'}")
    print(f"JSON: {out/'thermal_fem.json'}")
    return 0 if (bias["total_w"] > 0 and fast["pass_"]) else 1


if __name__ == "__main__":
    raise SystemExit(main())
