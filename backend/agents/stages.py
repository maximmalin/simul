def _chat_plain(system: str, user: str) -> str | None:
    """Простой ход без инструментов (писатель/дебагер/оптимизатор ТЗ)."""
    if not llm.enabled():
        return None
    try:
        turn = llm_race.chat([{"role": "system", "content": system},
                                {"role": "user", "content": user}],
                               temperature=0.1, max_tokens=8000,
                               timeout=STAGE_TIMEOUT)
        return turn.text if turn else None
    except Exception:                                   # noqa: BLE001
        return None


